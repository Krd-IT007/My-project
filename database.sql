CREATE DATABASE IF NOT EXISTS QuanLyTinTuc
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;
USE QuanLyTinTuc;
CREATE TABLE DanhMuc (
MaDM INT AUTO_INCREMENT PRIMARY KEY,
TenDM VARCHAR(100) NOT NULL,
TrangThai TINYINT NOT NULL DEFAULT 1,
CONSTRAINT chk_trangthai
CHECK (TrangThai IN (0, 1))
) ENGINE=InnoDB;
CREATE TABLE BaiViet (
MaBV INT AUTO_INCREMENT PRIMARY KEY,
TieuDe VARCHAR(200) NOT NULL,
NoiDung TEXT NOT NULL,
DM INT NOT NULL,
CONSTRAINT fk_baiviet_danhmuc
FOREIGN KEY (DM)
REFERENCES DanhMuc(MaDM)
ON UPDATE CASCADE
ON DELETE RESTRICT
) ENGINE=InnoDB;
SHOW TABLES;
DESCRIBE DanhMuc;
DESCRIBE BaiViet;